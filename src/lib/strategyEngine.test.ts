test('generateEvidenceDrivenStrategy builds architecture from real crawl, services, clusters, gaps, and ONLY approved locations', () => {
  const input = makeBaseInput();
  const bundle = generateEvidenceDrivenStrategy(input);

  assert.equal(bundle.evidenceReadiness.overallReadiness, 'Ready');
  assert.ok(bundle.objectives.length >= 3);

  // Only owner-approved Austin location page is created; unapproved Houston is excluded
  const locPages = bundle.pages.filter((p) => p.pageType === 'location');
  assert.equal(locPages.length, 1);
  assert.ok(locPages[0].targetGeography?.includes('Austin'));
  assert.equal(
    bundle.pages.some((p) => p.targetGeography?.includes('Houston')),
    false,
  );

  // Crawl-confirmed orphan page (/blog/implant-recovery-guide) is flagged with existsInCrawl=false and 0 inbound links
  const orphanRec = bundle.internalLinks.find(
    (l) =>
      l.linkCategory === 'orphan_rescue' &&
      l.targetUrl.includes('/blog/implant-recovery-guide'),
  );
  assert.ok(orphanRec, 'Expected orphan_rescue link recommendation for crawled orphan page');
  assert.equal(orphanRec.existsInCrawl, false);
  assert.equal(orphanRec.currentInboundCount, 0);

  // Dead-end page (/services/dental-implants) with 0 outbound links gets weak_link_fix
  assert.ok(
    bundle.internalLinks.some(
      (l) =>
        l.linkCategory === 'weak_link_fix' &&
        l.sourceUrl.includes('/services/dental-implants'),
    ),
  );

  // Topical coverage cleanly separates verified_existing vs recommended_opportunity
  assert.ok(
    bundle.topicalClusters.some(
      (c) => c.coverageClassification === 'verified_existing',
    ),
  );
  assert.ok(
    bundle.topicalClusters.some(
      (c) => c.coverageClassification === 'recommended_opportunity',
    ),
  );

  // Every roadmap item explicitly labels effort as an estimate
  assert.ok(bundle.roadmapItems.length >= 3);
  for (const item of bundle.roadmapItems) {
    assert.ok(item.estimatedEffort.startsWith('Estimate:'));
  }
});

